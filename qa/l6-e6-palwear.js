async page => {
  page.setDefaultNavigationTimeout(120000)
  await page.setViewportSize({ width: 1280, height: 760 })
  await page.addInitScript(() => { try { localStorage.clear() } catch (e) {} })
  await page.addInitScript(() => { try { localStorage.setItem('capy3.prefs.v1', JSON.stringify({ v: 1, pf: 1 })) } catch (e) {} })
  await page.goto('http://localhost:5190/')
  await page.waitForTimeout(6000)
  await page.evaluate(() => { const b = document.querySelector('.capyui-go'); if (b) b.click() })
  await page.waitForTimeout(6500)
  await page.evaluate(() => window.__capy.hud.cross('palawan'))
  await page.waitForTimeout(9000)
  await page.keyboard.down('KeyS'); await page.waitForTimeout(2200); await page.keyboard.up('KeyS')
  await page.waitForTimeout(7000)
  await page.screenshot({ path: 'qa/l6-e6-wear-palawan-2.png' })
  await page.evaluate(() => window.__capy.hud.cross('hanoi'))
  await page.waitForTimeout(9000)
  await page.keyboard.down('KeyW'); await page.waitForTimeout(3200); await page.keyboard.up('KeyW')
  await page.waitForTimeout(3000)
  await page.screenshot({ path: 'qa/l6-e6-hanoi-lake.png' })
  const out = await page.evaluate(() => { const g = window.__capy; return { biome: g.biome.current, capy: [g.capy.body.position.x, g.capy.body.position.z], err: g.state.lastError ? String(g.state.lastError) : null } })
  await page.evaluate((o) => fetch('/shot?name=l6-e6-palwear.json', { method: 'POST', body: btoa(unescape(encodeURIComponent(JSON.stringify(o)))) }), out)
}
