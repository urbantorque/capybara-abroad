async page => {
  page.setDefaultNavigationTimeout(120000)
  await page.setViewportSize({ width: 1280, height: 760 })
  await page.addInitScript(() => { try { localStorage.clear() } catch (e) {} })
  await page.addInitScript(() => { try { localStorage.setItem('capy3.prefs.v1', JSON.stringify({ v: 1, pf: 1 })) } catch (e) {} })
  await page.goto('http://localhost:5190/')
  await page.waitForTimeout(6000)
  await page.evaluate(() => { const b = document.querySelector('.capyui-go'); if (b) b.click() })
  await page.waitForTimeout(6500)
  await page.evaluate(() => window.__capy.hud.cross('cave'))
  await page.waitForTimeout(9000)
  await page.keyboard.down('KeyW'); await page.waitForTimeout(3200); await page.keyboard.up('KeyW')
  await page.waitForTimeout(14000)
  const clip = { x: 300, y: 40, width: 420, height: 320 }
  await page.screenshot({ path: 'qa/l7-e4-cavezoom-on.png', clip })
  await page.evaluate(() => { window.__capy.state.noTri = true })
  await page.waitForTimeout(350)
  await page.screenshot({ path: 'qa/l7-e4-cavezoom-notri.png', clip })
  await page.evaluate(() => { window.__capy.state.noTri = false })
  await page.waitForTimeout(350)
  await page.screenshot({ path: 'qa/l7-e4-cavezoom-on2.png', clip })
  const out = await page.evaluate(() => { const g = window.__capy; return { cam: g.camera.position.toArray(), dpr: window.devicePixelRatio, w: g.renderer.domElement.width, h: g.renderer.domElement.height, err: g.state.lastError || null } })
  await page.evaluate((o) => fetch('/shot?name=l7-e4-cavezoom.json', { method: 'POST', body: btoa(unescape(encodeURIComponent(JSON.stringify(o)))) }), out)
}
