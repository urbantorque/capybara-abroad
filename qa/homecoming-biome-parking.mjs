// Exercise the shipped owner with the actual bundled scene graph.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import * as THREE from '../vendor/three.module.js';
const text = readFileSync('src/main.js', 'utf8');
const start = text.indexOf('function mainMakeBiomes(game)');
const end = text.indexOf('\n  return biome;\n}', start) + '\n  return biome;\n}'.length;
assert(start >= 0 && end > start);
const make = vm.runInNewContext('(' + text.slice(start, end) + ')', { console, mainReport() {} });
const world = { bodies: [], addBody(b) { if (!this.bodies.includes(b)) this.bodies.push(b); },
  removeBody(b) { const i = this.bodies.indexOf(b); if (i >= 0) this.bodies.splice(i, 1); } };
const game = { scene: new THREE.Scene(), world, events: { emit() {} } };
const biome = make(game); biome._patchWorld();
let checks = 0;
function check(ok, label) { assert(ok, label); checks++; }
const root = new THREE.Group(), child = new THREE.Object3D(), hidden = new THREE.Object3D();
root.add(child); hidden.visible = false;
const body = {};
biome.capture('sydney', () => { game.scene.add(root, hidden); world.addBody(body); });
let visits = 0;
const update = child.updateMatrixWorld;
child.updateMatrixWorld = function (...args) { visits++; return update.apply(this, args); };
game.scene.updateMatrixWorld(true);
check(visits === 1, 'active child updates');
biome.attach('sydney', false);
game.scene.updateMatrixWorld(true);
check(visits === 1, 'sleeping child not traversed');
check(root.parent === null && !root.visible, 'sleeping root detached and hidden');
check(world.bodies.length === 0, 'sleeping body removed');
root.position.x = 7; child.position.x = 2; root.updateMatrixWorld(true);
check(child.matrixWorld.elements[12] === 9, 'explicit sleeping world query remains correct');
biome.attach('sydney', false);
biome._setTag('hanoi');
biome.attach('sydney', true);
check(root.parent === game.scene && root.visible && !hidden.visible, 'original visibility restored after repeated detach');
check(world.bodies.length === 1, 'body restored once');
biome.attach('hanoi', false);
check(world.bodies.includes(body), 'body restore bypasses active capture');
check(!biome.objectsOf('hanoi')?.includes(root), 'restore bypasses active capture');
check(biome.objectsOf('sydney').length === 2, 'restore does not grow owner array');
child.position.x = 4; game.scene.updateMatrixWorld(true);
check(child.matrixWorld.elements[12] === 11, 'returned rig still animates');
biome.attach('sydney', false); biome.disown(hidden); biome.attach('sydney', true);
check(hidden.parent === null && biome.objectsOf('sydney').length === 1, 'disowned parked prop never resurrects');
biome.attach('sydney', false);
const carrier = new THREE.Group(); carrier.add(root); game.scene.add(carrier);
biome.attach('sydney', true);
check(root.parent === carrier, 'new parent not stolen on return');
carrier.remove(root); biome.disown(root);
let attempts = 0;
biome.register('broken', { ensureBuilt() { game.scene.add(new THREE.Object3D()); if (++attempts === 1) throw Error('fixture'); } });
check(biome.switchTo('broken') === false, 'failed build rolls back');
check(biome.current === 'sydney' && biome.objectsOf('broken').length === 0, 'failed owner cleared');
check(biome.switchTo('broken') === true && biome.objectsOf('broken').length === 1, 'retry owns only rebuilt object');
const rebuilt = biome.objectsOf('broken')[0];
biome.attach('broken', false); biome.attach('broken', true);
check(rebuilt.parent === game.scene && game.scene.children.filter(o => o === rebuilt).length === 1, 'retry return attaches once');
console.log('homecoming biome parking: ' + checks + ' checks passed');
