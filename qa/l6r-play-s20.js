async page => {
  const samp = []
  const sample = async (tag) => samp.push({ tag, ...(await page.evaluate(() => { const g = window.__capy; const p = g.capy.body.position; const v = g.capy.body.velocity; return { pos: [p.x, p.y, p.z].map(n => +n.toFixed(2)), spd: +Math.hypot(v.x, v.z).toFixed(2), vy: +v.y.toFixed(2) } })) })
  await page.keyboard.down('KeyW')
  await page.waitForTimeout(1500)
  await sample('walk')
  await page.keyboard.down('ShiftLeft')
  await page.waitForTimeout(1500)
  await sample('run')
  await page.keyboard.press('Space')
  await page.waitForTimeout(250)
  await sample('hop+0.25')
  await page.screenshot({ path: 'qa/l6r-play-45.png' })
  await page.waitForTimeout(600)
  await sample('hop+0.85')
  await page.keyboard.down('KeyG')
  await page.waitForTimeout(600)
  await sample('slide')
  await page.screenshot({ path: 'qa/l6r-play-46.png' })
  await page.waitForTimeout(1000)
  await page.keyboard.up('KeyG')
  await page.keyboard.up('ShiftLeft')
  await page.keyboard.up('KeyW')
  await page.waitForTimeout(1000)
  await sample('stop')
  await page.screenshot({ path: 'qa/l6r-play-47.png' })
  await page.evaluate((o) => fetch('/shot?name=l6r-play-s20.json', { method: 'POST', body: btoa(unescape(encodeURIComponent(JSON.stringify(o)))) }), samp)
}
